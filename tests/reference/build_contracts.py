def load_spec() -> dict[str, Any]:
    raw = SPEC_PATH.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SPEC_SHA256:
        raise SystemExit(f"{SPEC_PATH.name} changed: sha256 {digest}, expected {SPEC_SHA256}")
    return json.loads(raw)


def snake(name: str) -> str:
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def operation_id_for(method: str, path: str) -> str:
    parts = [p for p in path.split("/") if p and p != "v1"]
    words = [snake(p.strip("{}")) for p in parts]
    return "_".join([method.lower(), *words])


