def ref_name(schema: dict[str, Any]) -> str:
    return str(schema.get("$ref", "")).rsplit("/", 1)[-1]


def clean(text: str | None, limit: int = 900) -> str:
    value = " ".join(str(text or "").split())
    return value if len(value) <= limit else value[: limit - 1] + "…"


def convert_schema(
    spec: dict[str, Any], schema: dict[str, Any], depth: int, seen: tuple[str, ...] = ()
) -> dict[str, Any]:
    """An OpenAPI schema as a contract schema: refs resolved, only executable keywords."""
    name = ref_name(schema)
    if name:
        if name in seen or depth < 0:
            return {"type": "object", "additionalProperties": True}
        target = spec["components"]["schemas"][name]
        converted = convert_schema(spec, target, depth, (*seen, name))
        if schema.get("description") and "description" not in converted:
            converted["description"] = clean(schema["description"], 300)
        return converted
    out: dict[str, Any] = {}
    for key, value in schema.items():
        if key in _KEPT_KEYWORDS:
            out[key] = clean(value, 300) if key == "description" else value
    kind = schema.get("type")
    if kind is None and "properties" in schema:
        kind = out["type"] = "object"
    if kind == "object":
        properties = schema.get("properties") or {}
        if depth <= 0 or not properties:
            out["additionalProperties"] = True
            if depth <= 0:
                return out
        if properties:
            out["properties"] = {
                key: convert_schema(spec, value, depth - 1, seen)
                for key, value in properties.items()
            }
            out["additionalProperties"] = True
        required = [r for r in schema.get("required") or [] if r in properties]
        if required:
            out["required"] = required
    elif kind == "array":
        items = schema.get("items") or {}
        out["items"] = convert_schema(spec, items, depth - 1, seen) if depth > 0 else {}
    if "example" in schema and "examples" not in out and depth >= 0:
        example = schema["example"]
        if isinstance(example, (str, int, float, bool)):
            out["examples"] = [example]
    return out


def _filter_fields(description: str) -> list[str]:
    match = re.search(r"Fields available for filtering:\s*(.*)", description or "")
    if not match:
        return []
    return [f for f in re.split(r"[\s,]+", match.group(1).strip()) if re.fullmatch(r"\w+", f)]


def _response(op: dict[str, Any]) -> tuple[str, dict[str, Any]]:
    """(content type, schema) of the success response."""
    for code in ("200", "201", "204"):
        response = op.get("responses", {}).get(code)
        if response is None:
            continue
        for content_type, value in (response.get("content") or {}).items():
            return content_type, value.get("schema") or {}
        return "", {}
    return "", {}


def endpoint_rows(spec: dict[str, Any] | None = None) -> list[dict[str, Any]]:
    """One row per documented endpoint, sorted by group and path."""
    spec = spec or load_spec()
    rows: list[dict[str, Any]] = []
    for path, item in spec["paths"].items():
        for method, op in item.items():
            if method not in {"get", "post", "put", "patch", "delete"}:
                continue
            params = op.get("parameters") or []
            names = {p["name"] for p in params}
            paged = method == "get" and {"page", "size", "filter"} <= names
            path_params = [p for p in params if p.get("in") == "path"]
            query_params = [
                p
                for p in params
                if p.get("in") == "query" and not (paged and p["name"] in PAGING_PARAMS)
            ]
            unknown = [
                p["name"]
                for p in params
                if p.get("in") == "header" and p["name"].lower() not in SKIPPED_HEADER_PARAMS
            ]
            if unknown or any(p.get("in") not in {"path", "query", "header"} for p in params):
                raise SystemExit(f"unhandled parameter on {method} {path}: {unknown}")
            body = (op.get("requestBody") or {}).get("content", {}).get("application/json")
            if op.get("requestBody") and body is None:
                raise SystemExit(f"unhandled request body on {method} {path}")
            content_type, response_schema = _response(op)
            tag = (op.get("tags") or ["-"])[0]
            rows.append(
                {
                    "operation_id": operation_id_for(method, path),
                    "openapi_operation_id": op.get("operationId", ""),
                    "tag": tag,
                    "http_method": method.upper(),
                    "path": path,
                    "summary": clean(op.get("summary") or "", 120),
                    "description": clean(op.get("description"), 600),
                    "group": GROUP_TITLES.get(tag, tag),
                    "write": method != "get",
                    "paged": paged,
                    "filter_fields": _filter_fields(op.get("description", "")) if paged else [],
                    "path_params": path_params,
                    "query_params": query_params,
                    "body": body,
                    "body_required": bool((op.get("requestBody") or {}).get("required")),
                    "binary": content_type == "application/octet-stream",
                    "response_schema": response_schema,
                }
            )
    rows.sort(key=lambda r: (r["group"], r["path"], r["http_method"]))
    ids = [r["operation_id"] for r in rows]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate operation ids")
    return rows


