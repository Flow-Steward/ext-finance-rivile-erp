def payload_kind(row: dict[str, Any]) -> str:
    """Which output carries the answer; must agree with endpoint_outputs()."""
    names = {o["name"] for o in endpoint_outputs(load_spec(), row)}
    if row["binary"]:
        return "file"
    if row["paged"]:
        return "list"
    for name in ("records", "value", "record"):
        if name in names:
            return name
    raise SystemExit(f"no payload output for {row['operation_id']}")


def runtime_registry(rows: list[dict[str, Any]]) -> str:
    lines = [
        '"""Closed registry of every Rivile ERP Public API endpoint this bundle exposes.',
        "",
        "Generated by tests/reference/build_contracts.py — do not edit by hand.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from .models import Endpoint",
        "",
        f'SPEC_SHA256 = "{SPEC_SHA256}"',
        "",
        "ENDPOINTS: tuple[Endpoint, ...] = (",
    ]
    for r in rows:
        path_params = tuple(
            (
                snake(p["name"]),
                p["name"],
                "uuid" if (p.get("schema") or {}).get("format") == "uuid" else "code",
            )
            for p in r["path_params"]
        )
        query_params = tuple(
            (
                snake(p["name"]),
                p["name"],
                _value_type(p.get("schema") or {}),
                bool(p.get("required")),
            )
            for p in r["query_params"]
        )
        lines.append(
            "    Endpoint("
            f"operation_id={r['operation_id']!r}, http_method={r['http_method']!r}, "
            f"path={r['path']!r}, write={r['write']!r}, paged={r['paged']!r}, "
            f"has_body={r['body'] is not None!r}, body_required={r['body_required']!r}, "
            f"binary={r['binary']!r}, path_params={path_params!r}, "
            f"query_params={query_params!r}, filter_fields={tuple(r['filter_fields'])!r}, "
            f"payload={payload_kind(r)!r}, "
            f"title={r['summary']!r}, group={r['group']!r}),"
        )
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def dump(path: Path, payload: Any) -> None:
    text = yaml.safe_dump(payload, sort_keys=False, allow_unicode=True, width=100)
    path.write_text(GENERATED_HEADER + text, encoding="utf-8")


def splice_effects(effects: list[dict[str, Any]]) -> None:
    """Replace ``external_effects`` in extension.yaml, keeping every other key and its order."""
    manifest = ROOT / "extension.yaml"
    data = yaml.safe_load(manifest.read_text(encoding="utf-8"))
    rebuilt: dict[str, Any] = {}
    for key, value in data.items():
        if key == "runtime" and "external_effects" not in rebuilt:
            rebuilt["external_effects"] = effects
        if key != "external_effects":
            rebuilt[key] = value
    rebuilt.setdefault("external_effects", effects)
    manifest.write_text(
        yaml.safe_dump(rebuilt, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8"
    )


def outputs() -> dict[str, Any]:
    spec = load_spec()
    rows = endpoint_rows(spec)
    ops = build_operations(spec, rows)
    return {
        "rows": rows,
        "operations": ops,
        "actions": [action_for(op) for op in ops],
        "forms": [form_for(op, option_labels(rows)) for op in ops],
        "artifact_policies": artifact_policies(rows),
        "effects": external_effects(ops),
        "registry": runtime_registry(rows),
        "api_page": build_ui_pages.api_page(ops, rows),
        "changelog_page": build_ui_pages.changelog_page(),
    }


def main() -> None:
    built = outputs()
    dump(ROOT / "contracts" / "operation_manifest.yaml", {"operations": built["operations"]})
    dump(ROOT / "contracts" / "step_ui_manifest.yaml", {"forms": built["forms"]})
    dump(
        ROOT / "contracts" / "artifact_policies.yaml",
        {"artifact_policies": built["artifact_policies"]},
    )
    dump(ROOT / "ui" / "actions" / "actions.yaml", {"actions": built["actions"]})
    for name, key in (("rivile-erp-api.yaml", "api_page"), ("changelog.yaml", "changelog_page")):
        build_ui_pages.dump_page(ROOT / "ui" / "pages" / name, GENERATED_HEADER, built[key])
    (ROOT / "runtime" / "endpoints.py").write_text(built["registry"], encoding="utf-8")
    splice_effects(built["effects"])
    print(
        f"{len(built['rows'])} Rivile ERP endpoints, {len(built['operations'])} operations, "
        f"{len(built['effects'])} external effects"
    )


if __name__ == "__main__":
    main()
